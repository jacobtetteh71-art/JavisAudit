// Shared PDF layouts so that anything the owner prints out —
// a stock summary, a bid/tender document package cover sheet —
// looks consistent, with the same letterhead, fonts, and spacing.
// ============================================================

import 'dart:io';

import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;
import 'package:printing/printing.dart';

import '../models/models.dart';
import 'utils.dart';

// Loads the business logo (the same photo used as the profile
// picture elsewhere in the app) as something pw.Image can render.
// Returns null silently if there's no photo yet, or the file has
// gone missing — printables should never crash just because a
// logo isn't set, they just print without one.
pw.ImageProvider? _loadLogo(BusinessProfile? profile) {
  final path = profile?.profileImagePath;
  if (path == null || path.isEmpty) return null;
  final file = File(path);
  if (!file.existsSync()) return null;
  try {
    return pw.MemoryImage(file.readAsBytesSync());
  } catch (_) {
    return null;
  }
}

// A consistent header block used at the top of every uniform
// document — logo (if the owner has set one), business name,
// location, and a document title. This is what turns a printout
// into something that reads as the BUSINESS's own document rather
// than a generic app export.
pw.Widget buildLetterhead(BusinessProfile? profile, String documentTitle) {
  final logo = _loadLogo(profile);

  return pw.Column(
    crossAxisAlignment: pw.CrossAxisAlignment.start,
    children: [
      pw.Row(
        crossAxisAlignment: pw.CrossAxisAlignment.start,
        children: [
          if (logo != null) ...[
            pw.Container(
              width: 48, height: 48,
              decoration: pw.BoxDecoration(
                shape: pw.BoxShape.circle,
                image: pw.DecorationImage(image: logo, fit: pw.BoxFit.cover),
              ),
            ),
            pw.SizedBox(width: 12),
          ],
          pw.Expanded(
            child: pw.Column(
              crossAxisAlignment: pw.CrossAxisAlignment.start,
              children: [
                pw.Text(profile?.businessName ?? 'JavisAudit',
                    style: pw.TextStyle(fontSize: 20, fontWeight: pw.FontWeight.bold)),
                if (profile?.location != null && profile!.location!.isNotEmpty)
                  pw.Text(profile.location!, style: const pw.TextStyle(fontSize: 10, color: PdfColors.grey700)),
                if (profile?.ownerName != null && profile!.ownerName.isNotEmpty)
                  pw.Text('Owner: ${profile.ownerName}', style: const pw.TextStyle(fontSize: 10, color: PdfColors.grey700)),
                if (profile?.phone != null && profile!.phone!.isNotEmpty)
                  pw.Text('Tel: ${profile.phone}', style: const pw.TextStyle(fontSize: 10, color: PdfColors.grey700)),
              ],
            ),
          ),
        ],
      ),
      pw.SizedBox(height: 10),
      pw.Text(documentTitle.toUpperCase(),
          style: pw.TextStyle(fontSize: 13, fontWeight: pw.FontWeight.bold, color: PdfColors.grey800)),
      pw.Text('Generated ${AppFormat.displayDate(AppFormat.today())}',
          style: const pw.TextStyle(fontSize: 9, color: PdfColors.grey600)),
      pw.Divider(thickness: 1.2, color: PdfColors.grey800),
      pw.SizedBox(height: 10),
    ],
  );
}

// A small, deliberately understated footer printed on every page
// of every JavisAudit document — the business's own branding (via
// buildLetterhead above) is what's meant to be visible at a glance;
// this is a quiet "generated by" line, not a second logo. Pass to
// MultiPage/Page's `footer:` parameter.
pw.Widget buildFooter(BusinessProfile? profile, pw.Context context) {
  return pw.Container(
    alignment: pw.Alignment.center,
    margin: const pw.EdgeInsets.only(top: 8),
    padding: const pw.EdgeInsets.only(top: 4),
    decoration: const pw.BoxDecoration(
      border: pw.Border(top: pw.BorderSide(width: 0.5, color: PdfColors.grey400)),
    ),
    child: pw.Text(
      '${profile?.businessName ?? "JavisAudit"}'
      '${(profile?.location != null && profile!.location!.isNotEmpty) ? " — ${profile.location}" : ""}'
      '   •   Generated via JavisAudit   •   Page ${context.pageNumber} of ${context.pagesCount}',
      style: const pw.TextStyle(fontSize: 7, color: PdfColors.grey500),
    ),
  );
}


// ── Stock Summary ─────────────────────────────────────────
Future<void> printStockSummary(List<InventoryItem> items, {BusinessProfile? profile}) async {
  final pdf = pw.Document();
  final totalStockValue = items.fold<double>(0, (s, i) => s + i.stockValue);

  pdf.addPage(
    pw.MultiPage(
      pageFormat: PdfPageFormat.a4,
      margin: const pw.EdgeInsets.all(32),
      header: (context) => context.pageNumber == 1
          ? buildLetterhead(profile, 'Stock Summary')
          : pw.SizedBox(),
      footer: (context) => buildFooter(profile, context),
      build: (context) => [
        pw.Table(
          border: pw.TableBorder.all(color: PdfColors.grey400, width: 0.5),
          columnWidths: const {
            0: pw.FlexColumnWidth(3),
            1: pw.FlexColumnWidth(1.3),
            2: pw.FlexColumnWidth(1.5),
            3: pw.FlexColumnWidth(1.5),
            4: pw.FlexColumnWidth(1.5),
          },
          children: [
            pw.TableRow(
              decoration: const pw.BoxDecoration(color: PdfColors.grey300),
              children: [
                _cell('Item', isHeader: true),
                _cell('In Stock', isHeader: true),
                _cell('Cost/Unit', isHeader: true),
                _cell('Sells For', isHeader: true),
                _cell('Stock Value', isHeader: true),
              ],
            ),
            ...items.map((item) => pw.TableRow(children: [
                  _cell(item.name),
                  _cell('${item.stockQuantity}${item.unit != null ? " ${item.unit}" : ""}'),
                  _cell(AppFormat.pdfCurrency(item.costPrice)),
                  _cell(AppFormat.pdfCurrency(item.sellingPrice)),
                  _cell(AppFormat.pdfCurrency(item.stockValue)),
                ])),
          ],
        ),
        pw.SizedBox(height: 16),
        pw.Container(
          padding: const pw.EdgeInsets.symmetric(vertical: 8),
          decoration: const pw.BoxDecoration(
            border: pw.Border(top: pw.BorderSide(width: 1, color: PdfColors.black)),
          ),
          child: pw.Row(
            mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
            children: [
              pw.Text('TOTAL STOCK VALUE (at cost)', style: pw.TextStyle(fontSize: 12, fontWeight: pw.FontWeight.bold)),
              pw.Text(AppFormat.pdfCurrency(totalStockValue), style: pw.TextStyle(fontSize: 12, fontWeight: pw.FontWeight.bold)),
            ],
          ),
        ),
      ],
    ),
  );

  await Printing.sharePdf(bytes: await pdf.save(), filename: 'Stock_Summary_${AppFormat.today()}.pdf');
}

pw.Widget _cell(String text, {bool isHeader = false}) {
  return pw.Padding(
    padding: const pw.EdgeInsets.all(5),
    child: pw.Text(text, style: pw.TextStyle(fontSize: 9, fontWeight: isHeader ? pw.FontWeight.bold : pw.FontWeight.normal)),
  );
}
